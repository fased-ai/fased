#!/usr/bin/env node

import fs from "node:fs";
import fsp from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "config", "signer-protocol-v2.json");
const check = process.argv.includes("--check");
const contract = JSON.parse(await fsp.readFile(sourcePath, "utf8"));

function assertStringList(value, label) {
  if (
    !Array.isArray(value) ||
    value.length === 0 ||
    value.some((entry) => typeof entry !== "string" || !entry)
  ) {
    throw new Error(`${label} must be a non-empty string array`);
  }
  if (new Set(value).size !== value.length) {
    throw new Error(`${label} must not contain duplicates`);
  }
}

if (
  contract?.protocol?.current !== 2 ||
  contract.protocol.min !== 2 ||
  contract.protocol.max !== 2 ||
  !Number.isSafeInteger(contract.nativeFeeReservationLamports) ||
  contract.nativeFeeReservationLamports <= 0
) {
  throw new Error("signer protocol-v2 contract contains an invalid protocol or fee reservation");
}
assertStringList(contract.intentTypes, "intentTypes");
assertStringList(contract.operationStates, "operationStates");
assertStringList(contract.features, "features");
assertStringList(contract.clientRequiredFeatures, "clientRequiredFeatures");
if (contract.clientRequiredFeatures.some((feature) => !contract.features.includes(feature))) {
  throw new Error("clientRequiredFeatures must be a subset of advertised features");
}

const { clientRequiredFeatures, ...advertisedContract } = contract;
function javascriptLiteral(value, depth = 0) {
  const indent = "  ".repeat(depth);
  const childIndent = "  ".repeat(depth + 1);
  if (Array.isArray(value)) {
    const inline = `[${value.map((entry) => javascriptLiteral(entry, depth + 1)).join(", ")}]`;
    if (inline.length + childIndent.length <= 80) {
      return inline;
    }
    return `[\n${value.map((entry) => `${childIndent}${javascriptLiteral(entry, depth + 1)},`).join("\n")}\n${indent}]`;
  }
  if (value && typeof value === "object") {
    return `{\n${Object.entries(value)
      .map(([key, entry]) => `${childIndent}${key}: ${javascriptLiteral(entry, depth + 1)},`)
      .join("\n")}\n${indent}}`;
  }
  return JSON.stringify(value);
}

const advertisedLiteral = javascriptLiteral(advertisedContract);
const requiredLiteral = javascriptLiteral(clientRequiredFeatures);
const javascript = `// Generated by scripts/generate-signer-protocol-v2.mjs. Do not edit.\nexport const SIGNER_PROTOCOL_V2 = Object.freeze(${advertisedLiteral});\nexport const SIGNER_PROTOCOL_V2_REQUIRED_CLIENT_FEATURES = Object.freeze(${requiredLiteral});\n`;
const typescript = `// Generated by scripts/generate-signer-protocol-v2.mjs. Do not edit.\nexport const SIGNER_PROTOCOL_V2 = ${advertisedLiteral} as const;\nexport const SIGNER_PROTOCOL_V2_REQUIRED_CLIENT_FEATURES = ${requiredLiteral} as const;\n`;
const quoteGo = (value) => JSON.stringify(value);
const goList = (values) => values.map((value) => `\t\t${quoteGo(value)},`).join("\n");
const golang = `// Code generated by scripts/generate-signer-protocol-v2.mjs; DO NOT EDIT.\n\npackage main\n\nvar signerV2Capabilities = signerCapabilitiesV2{\n\tProtocol:                     signerProtocolRangeV2{Current: ${contract.protocol.current}, Min: ${contract.protocol.min}, Max: ${contract.protocol.max}},\n\tNativeFeeReservationLamports: ${contract.nativeFeeReservationLamports},\n\tIntentTypes: []string{\n${goList(contract.intentTypes)}\n\t},\n\tOperationStates: []string{\n${goList(contract.operationStates)}\n\t},\n\tFeatures: []string{\n${goList(contract.features)}\n\t},\n}\n`;

const outputs = new Map([
  [path.join(root, "scripts", "signer-protocol-v2.generated.mjs"), javascript],
  [path.join(root, "src", "wallet", "signer-protocol-v2.generated.ts"), typescript],
  [path.join(root, "tools", "fased-signerd", "protocol_v2_generated.go"), golang],
]);

let stale = false;
for (const [outputPath, content] of outputs) {
  if (check) {
    const existing = fs.existsSync(outputPath) ? await fsp.readFile(outputPath, "utf8") : "";
    if (existing !== content) {
      console.error(
        `${path.relative(root, outputPath)} is stale; run pnpm signer:protocol:generate`,
      );
      stale = true;
    }
  } else {
    await fsp.writeFile(outputPath, content);
  }
}
if (stale) {
  process.exitCode = 1;
}
