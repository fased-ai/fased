#!/usr/bin/env node

import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contractPath = path.join(
  root,
  "src/agents/protocol-generation/fased-agent-capital-interface.v1.json",
);
const tsPath = path.join(root, "src/agents/fased-agent-capital-contract.generated.ts");
const goPath = path.join(root, "tools/fased-signerd/agent_capital_contract_generated.go");
const programId = "FASJ6eaNMEe6K3DdXBT6ZbkfDFSjGBtxbNTVn9htXFKz"; // pragma: allowlist secret
const importMode = process.argv.includes("--import");
const checkMode = process.argv.includes("--check");
const sourceIndex = process.argv.indexOf("--agent-root");
const sourceRoot = sourceIndex >= 0 ? path.resolve(process.argv[sourceIndex + 1] ?? "") : null;
const commitIndex = process.argv.indexOf("--source-commit");
const sourceCommit = commitIndex >= 0 ? (process.argv[commitIndex + 1] ?? "") : "";
const treeIndex = process.argv.indexOf("--source-tree");
const sourceTree = treeIndex >= 0 ? (process.argv[treeIndex + 1] ?? "") : "";

if (importMode === checkMode || (importMode && (!sourceRoot || !sourceCommit || !sourceTree))) {
  throw new Error(
    "use exactly one mode: --import --agent-root <checkout> --source-commit <sha> --source-tree <sha> or --check",
  );
}

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const canonical = (value) => `${JSON.stringify(value, null, 2)}\n`;

function dataSize(args) {
  return (
    8 +
    args.reduce((size, arg) => {
      if (arg.type === "u64") {
        return size + 8;
      }
      if (arg.type === "u32") {
        return size + 4;
      }
      if (JSON.stringify(arg.type) === JSON.stringify({ array: ["u8", 32] })) {
        return size + 32;
      }
      if (JSON.stringify(arg.type) === JSON.stringify({ array: ["u32", 16] })) {
        return size + 64;
      }
      throw new Error(`unsupported Agent Capital argument type ${JSON.stringify(arg.type)}`);
    }, 0)
  );
}

function buildContract(repo) {
  const idlPath = path.join(repo, "idl/fased_agent_capital.json");
  const bytes = fs.readFileSync(idlPath);
  const idl = JSON.parse(bytes);
  if (idl.address !== programId) {
    throw new Error("Agent Capital program identity changed");
  }
  const expected = [
    "activate_capital_offer",
    "bind_satcoin_vault",
    "cancel_capital_offer",
    "claim_vault_sat",
    "commit_vault_cycle",
    "compact_vault_pending_cycle",
    "configure_vault_mining",
    "deposit_capital_offer",
    "deposit_capital_offer_generation",
    "finalize_vault_exit",
    "initialize_capital_offer",
    "record_vault_result",
    "refund_cancelled_position",
    "request_vault_exit",
    "reveal_vault_cycle",
    "succeed_empty_capital_offer",
  ];
  const names = idl.instructions.map((entry) => entry.name);
  if (JSON.stringify(names) !== JSON.stringify(expected)) {
    throw new Error("Agent Capital instruction surface changed");
  }
  return {
    $schema: "fased.agent-capital-interface.v1",
    source: {
      repository: "https://github.com/fased-ai/agent-protocol",
      commit: sourceCommit,
      tree: sourceTree,
      idlSha256: `sha256:${sha256(bytes)}`,
    },
    programId,
    generation: 1,
    instructions: idl.instructions.map((entry) => ({
      action: entry.name,
      discriminator: entry.discriminator,
      dataSize: dataSize(entry.args),
      args: entry.args,
      accounts: entry.accounts.map((account) => ({
        name: account.name,
        signer: account.signer === true,
        writable: account.writable === true,
        ...(account.address ? { address: account.address } : {}),
      })),
    })),
    accounts: idl.accounts.map((entry) => ({
      name: entry.name,
      discriminator: entry.discriminator,
    })),
  };
}

function tsSource(contract) {
  const generatedContract = JSON.stringify(contract, null, 2)
    .replace(
      /^(\s+"(?:commit|tree|idlSha256|programId)": "[^"]+"[,]?)$/gmu,
      "$1 // pragma: allowlist secret",
    )
    .replace(
      /^(\s+"address": "FASJ6eaNMEe6K3DdXBT6ZbkfDFSjGBtxbNTVn9htXFKz"[,]?)$/gmu, // pragma: allowlist secret
      "$1 // pragma: allowlist secret",
    );
  return `// Code generated by scripts/generate-fased-agent-capital-interface.mjs; DO NOT EDIT.\n\nexport const FASED_AGENT_CAPITAL_CONTRACT = ${generatedContract} as const;\n\nexport const FASED_AGENT_CAPITAL_PROGRAM_ID = FASED_AGENT_CAPITAL_CONTRACT.programId;\nexport type FasedAgentCapitalAction = (typeof FASED_AGENT_CAPITAL_CONTRACT.instructions)[number]["action"];\n`;
}

function goSource(contract) {
  const rows = contract.instructions
    .map((instruction) => {
      const accounts = instruction.accounts
        .map(
          (account) =>
            `{Name: ${JSON.stringify(account.name)}, IsSigner: ${account.signer}, IsWritable: ${account.writable}, Address: ${JSON.stringify(account.address ?? "")}}`,
        )
        .join(", ");
      return `${JSON.stringify(instruction.action)}: {Discriminator: [8]byte{${instruction.discriminator.join(", ")}}, DataSize: ${instruction.dataSize}, Accounts: []agentCapitalAccountContractV1{${accounts}}}`;
    })
    .join(",\n\t");
  return `// Code generated by scripts/generate-fased-agent-capital-interface.mjs; DO NOT EDIT.\npackage main\n\nconst agentCapitalProgramIDV1 = ${JSON.stringify(contract.programId)} // pragma: allowlist secret\n\ntype agentCapitalAccountContractV1 struct { Name string; IsSigner bool; IsWritable bool; Address string }\ntype agentCapitalInstructionContractV1 struct { Discriminator [8]byte; DataSize int; Accounts []agentCapitalAccountContractV1 }\n\nvar agentCapitalInstructionContractsV1 = map[string]agentCapitalInstructionContractV1{\n\t${rows},\n}\n`;
}

async function rendered(contract) {
  return {
    contract: (await format(path.basename(contractPath), canonical(contract))).code,
    ts: (await format(path.basename(tsPath), tsSource(contract))).code,
    go: goSource(contract),
  };
}

if (importMode) {
  const output = await rendered(buildContract(sourceRoot));
  fs.mkdirSync(path.dirname(contractPath), { recursive: true });
  fs.writeFileSync(contractPath, output.contract);
  fs.writeFileSync(tsPath, output.ts);
  fs.writeFileSync(goPath, output.go);
} else {
  const contract = JSON.parse(fs.readFileSync(contractPath, "utf8"));
  const output = await rendered(contract);
  for (const [file, expected] of [
    [contractPath, output.contract],
    [tsPath, output.ts],
  ]) {
    if (fs.readFileSync(file, "utf8") !== expected) {
      throw new Error(`${path.relative(root, file)} is not reproducibly generated`);
    }
  }
}
