export function lookupRefreshedModelCapability(
  provider: string,
  model: string,
): RefreshedModelCapability | undefined {
  const key = `${provider.trim()}/${model.trim()}`.toLowerCase();
  const refreshed = REFRESHED_MODEL_CAPABILITIES[key];
  if (!refreshed || (refreshed.tools === undefined && refreshed.json === undefined)) {
    return refreshed;
  }
  return {
    ...refreshed,
    capabilities: {
      ...refreshed.capabilities,
      ...(refreshed.tools === undefined ? {} : { tools: refreshed.tools }),
      ...(refreshed.json === undefined ? {} : { json: refreshed.json }),
    },
  };
}
